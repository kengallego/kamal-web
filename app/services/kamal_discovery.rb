# Finds the Kamal apps running on this server through the Docker socket and
# keeps a project for each one.
#
# Kamal labels app containers with service/role/destination and accessories
# with service="<app>-<name>". The deployed image usually contains the app's
# own config/deploy*.yml, which is used as is; otherwise a config is rebuilt
# from the containers and kamal-proxy routes. Discovered projects are
# read-only until their repository is connected, because a rebuilt config has
# no env or secrets and redeploying with it would break the app.
class KamalDiscovery
  App = Data.define(:service, :files, :versions, :config_source)
  Result = Data.define(:apps, :created, :updated, :error)

  GENERATED_HEADER = "# Generated by Kamal UI from the containers running on this server.\n" \
    "# Connect the project's repository in its settings to deploy.\n".freeze

  def initialize(docker: LocalDocker.new, host_address: self.class.host_address)
    @docker = docker
    @host_address = host_address
  end

  # The address Kamal UI uses to SSH into the server it runs on: the container's
  # default gateway, unless KAMAL_UI_HOST_ADDRESS says otherwise.
  def self.host_address
    ENV["KAMAL_UI_HOST_ADDRESS"].presence || default_gateway || "127.0.0.1"
  end

  def self.default_gateway
    File.readlines("/proc/net/route").drop(1).each do |line|
      _, destination, gateway = line.split
      return [ gateway.to_i(16) ].pack("V").unpack("C4").join(".") if destination == "00000000"
    end
    nil
  rescue Errno::ENOENT
    nil
  end

  def call
    return Result.new(apps: [], created: [], updated: [], error: "Docker is not reachable. Mount /var/run/docker.sock to detect apps on this server.") unless @docker.available?

    apps = discover
    created, updated = import(apps)
    Result.new(apps: apps, created: created, updated: updated, error: nil)
  rescue LocalDocker::Error => error
    Result.new(apps: [], created: [], updated: [], error: error.message)
  end

  def discover
    containers = @docker.kamal_containers
    own_service = own_service(containers)
    containers = containers.reject { |container| own_service && labels(container)["service"].to_s.then { |name| name == own_service || name.start_with?("#{own_service}-") } }
    apps = containers.select { |container| labels(container).key?("role") }.group_by { |container| labels(container)["service"] }
    return [] if apps.empty?

    routes = @docker.proxy_routes
    ssh_user = detect_ssh_user(containers)

    apps.filter_map do |service, app_containers|
      next if service.blank?

      accessories = containers.select do |container|
        name = labels(container)["service"].to_s
        !labels(container).key?("role") && name.start_with?("#{service}-")
      end
      versions = versions_for(service, app_containers)
      files = files_from_image(service, app_containers)
      source = files ? "image" : "generated"
      files ||= generated_files(service, app_containers, accessories, routes, ssh_user)
      App.new(service: service, files: files, versions: versions, config_source: source)
    end
  end

  def import(apps)
    created = []
    updated = []
    ignored = Setting.instance.ignored_services
    managed = Project.where.not(source_kind: "discovered").flat_map { |project| project.config_snapshots.values.map { |snapshot| snapshot["service"] } }

    apps.each do |app|
      project = Project.find_by(discovered_service: app.service)

      if project
        next unless project.discovered?
        next if project.discovered_file_map == app.files && project.discovered_versions == app.versions

        project.update!(discovered_files: app.files.to_json, discovered_versions: app.versions)
        updated << project
      elsif !ignored.include?(app.service) && !managed.include?(app.service)
        project = Project.create!(name: unique_name(app.service), source_kind: "discovered", discovered_service: app.service,
          discovered_files: app.files.to_json, discovered_versions: app.versions)
        created << project
      else
        next
      end

      sync(project)
    end

    [ created, updated ]
  end

  private
    def labels(container)
      container.dig("Config", "Labels") || {}
    end

    def running?(container)
      container.dig("State", "Running")
    end

    # Kamal UI is deployed with Kamal too. It never lists itself: managing it
    # from inside would stop the container running the command.
    def own_service(containers)
      container_name = ENV["KAMAL_CONTAINER_NAME"].to_s
      hostname = ENV["HOSTNAME"].to_s
      own = containers.find do |container|
        (container_name.present? && container["Name"].to_s.delete_prefix("/") == container_name) ||
          (hostname.length >= 12 && container["Id"].to_s.start_with?(hostname))
      end
      labels(own)["service"].presence if own
    end

    # Kamal names app containers <service>-<role>[-<destination>]-<version>.
    def versions_for(service, containers)
      containers.group_by { |container| labels(container)["destination"].to_s }.to_h do |destination, group|
        container = group.select { |c| running?(c) }.max_by { |c| c["Created"] } || group.max_by { |c| c["Created"] }
        role = labels(container)["role"]
        prefix = [ service, role, destination.presence ].compact.join("-") + "-"
        name = container["Name"].to_s.delete_prefix("/")
        [ destination, name.start_with?(prefix) ? name.delete_prefix(prefix) : nil ]
      end.compact
    end

    def files_from_image(service, containers)
      container = containers.select { |c| running?(c) }.max_by { |c| c["Created"] } || containers.first
      workdir = container.dig("Config", "WorkingDir").presence || "/"
      found = @docker.read_files(container["Id"], File.join(workdir, "config"))
        .select { |path, _| path.match?(%r{\Aconfig/deploy(\.[\w-]+)?\.yml\z}) }
      return if found.empty? || !found.key?("config/deploy.yml")
      return unless deploy_service(found["config/deploy.yml"]) == service

      secrets = @docker.read_files(container["Id"], File.join(workdir, ".kamal")).select { |path, _| path.match?(%r{\A\.kamal/secrets[\w.-]*\z}) }
      found.merge(secret_files(secrets))
    end

    def deploy_service(yaml)
      yaml[/^service:\s*["']?([\w.-]+)/, 1]
    end

    # Only the variable names are kept: values in an image's secrets file may run
    # commands (`$(cat config/master.key)`), so each becomes NAME=$NAME and is
    # filled from the project's environment variables instead.
    def secret_files(files)
      files = { ".kamal/secrets" => "" } if files.empty?
      files.transform_values do |content|
        names = content.to_s.scan(/^\s*(?:export\s+)?([A-Za-z_]\w*)=/).flatten | [ "KAMAL_REGISTRY_PASSWORD" ]
        names.map { |name| "#{name}=$#{name}\n" }.join
      end
    end

    def generated_files(service, containers, accessories, routes, ssh_user)
      running = containers.select { |c| running?(c) }.presence || containers
      sample = running.max_by { |c| c["Created"] }
      repository, server = split_image(sample.dig("Config", "Image"))

      base = {
        "service" => service,
        "image" => repository,
        "registry" => { "server" => server, "username" => "kamal-ui", "password" => [ "KAMAL_REGISTRY_PASSWORD" ] }.compact,
        "builder" => { "arch" => @docker.image_architecture(sample.dig("Config", "Image")) || "amd64" },
        "ssh" => { "user" => ssh_user }
      }
      if accessories.any?
        base["accessories"] = accessories.to_h do |accessory|
          [ labels(accessory)["service"].delete_prefix("#{service}-"), { "image" => accessory.dig("Config", "Image"), "host" => @host_address } ]
        end
      end

      by_destination = running.group_by { |c| labels(c)["destination"].to_s }
      files = {}
      if by_destination.keys == [ "" ]
        files["config/deploy.yml"] = base.merge(servers_and_proxy(service, "", by_destination[""], routes))
      else
        files["config/deploy.yml"] = base
        by_destination.each do |destination, group|
          files[destination.present? ? "config/deploy.#{destination}.yml" : "config/deploy.yml"] =
            (destination.present? ? {} : base).merge(servers_and_proxy(service, destination, group, routes))
        end
      end

      files.transform_values { |config| GENERATED_HEADER + config.to_yaml.delete_prefix("---\n") }
        .merge(".kamal/secrets" => "KAMAL_REGISTRY_PASSWORD=$KAMAL_REGISTRY_PASSWORD\n")
    end

    def servers_and_proxy(service, destination, containers, routes)
      roles = containers.map { |c| labels(c)["role"] }.uniq.sort_by { |role| role == "web" ? "" : role }
      config = { "servers" => roles.to_h { |role| [ role, { "hosts" => [ @host_address ] } ] } }
      config["primary_role"] = roles.first unless roles.include?("web")

      prefix = [ service, roles.first, destination.presence ].compact.join("-")
      route = routes.find { |r| r.service == prefix }
      if route && route.host.present?
        hosts = route.host.split(",").map(&:strip).reject(&:blank?)
        proxy = { "hosts" => hosts, "ssl" => route.tls.to_s.downcase.in?(%w[ yes true ]) }
        port = route.target.to_s[/:(\d+)\z/, 1]
        proxy["app_port"] = port.to_i if port && port != "80"
        config["proxy"] = proxy
      end
      config
    end

    # "ghcr.io/acme/app:abc123" => ["acme/app", "ghcr.io"]; Docker Hub images have no server.
    def split_image(image)
      name = image.to_s.sub(/@sha256:\h+\z/, "")
      name = name.sub(/:[\w.-]+\z/, "") if name.rpartition("/").last.include?(":")
      first, rest = name.split("/", 2)
      rest && (first.include?(".") || first.include?(":") || first == "localhost") ? [ rest, first ] : [ name, nil ]
    end

    # Kamal keeps per-app files in ~/.kamal on the host and bind-mounts some of
    # them, which reveals the SSH user it deploys with.
    def detect_ssh_user(containers)
      proxy = @docker.container("kamal-proxy")
      sources = ([ proxy ].compact + containers).flat_map { |c| Array(c["Mounts"]).map { |mount| mount["Source"].to_s } }
      sources.each do |source|
        return "root" if source.start_with?("/root/.kamal/")
        return Regexp.last_match(1) if source =~ %r{\A/home/([\w.-]+)/\.kamal/}
      end
      "root"
    end

    def unique_name(service)
      name = service
      suffix = 1
      name = "#{service}-#{suffix += 1}" while Project.exists?(name: name)
      name
    end

    def sync(project)
      ProjectWorkspace.new(project).sync!
    rescue ProjectWorkspace::Error, SshAgent::Error
      # Stored on the project and shown on its page.
    end
end
